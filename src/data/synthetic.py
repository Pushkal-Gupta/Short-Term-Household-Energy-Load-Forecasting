"""SYNTHETIC smart-meter data for software validation only.

Writes a CSV in the exact Low Carbon London column format so the real loader is exercised
end to end. Every household id starts with `SYNTH_` and the file name says `synthetic`, so
it can never be mistaken for the real dataset. Nothing produced from this file is a result.

The generator deliberately includes the defects the real cleaner has to handle:
`Null` readings, duplicate timestamps, a negative value, an implausible spike, and gaps.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

SYNTH_FILE = "synthetic_LCL_format_NOT_REAL.csv"


def make_synthetic_lcl(out_dir: Path, num_households: int = 12, start: str = "2013-01-01",
                       end: str = "2013-03-01", seed: int = 0) -> Path:
    rng = np.random.default_rng(seed)
    out_dir.mkdir(parents=True, exist_ok=True)
    idx = pd.date_range(start, end, freq="30min", inclusive="left")
    hours = (idx.hour + idx.minute / 60.0).to_numpy()
    dow = idx.dayofweek.values
    frames = []
    for h in range(num_households):
        base = rng.uniform(0.05, 0.35)
        # Three archetypes so that profile clustering has something to find.
        kind = h % 3
        morning = np.exp(-0.5 * ((hours - 7.5) / 1.0) ** 2) * (0.8 if kind == 0 else 0.25)
        evening = np.exp(-0.5 * ((hours - 19.0) / 1.5) ** 2) * (1.0 if kind != 2 else 0.35)
        daytime = np.exp(-0.5 * ((hours - 13.0) / 3.0) ** 2) * (0.6 if kind == 2 else 0.1)
        weekend = np.where(dow >= 5, 1.15, 1.0)
        scale = rng.uniform(0.5, 1.8)
        kwh = (base + scale * (morning + evening + daytime)) * weekend
        kwh = kwh * rng.lognormal(0.0, 0.25, size=len(idx))
        kwh = np.round(np.asarray(kwh, dtype=float), 3).astype(object)
        # Inject defects.
        gap = rng.integers(0, len(idx) - 20)
        kwh[gap:gap + int(rng.integers(1, 12))] = "Null"
        kwh[rng.integers(0, len(idx))] = -0.5
        kwh[rng.integers(0, len(idx))] = 55.0
        df = pd.DataFrame({
            "LCLid": f"SYNTH_{h:03d}",
            "stdorToU": "Std",
            "DateTime": idx.strftime("%Y-%m-%d %H:%M:%S.0000000"),
            "KWH/hh (per half hour) ": kwh,
        })
        dup = df.sample(5, random_state=seed + h)
        frames.extend([df, dup])
    out = pd.concat(frames).sample(frac=1.0, random_state=seed)  # unsorted on purpose
    path = out_dir / SYNTH_FILE
    out.to_csv(path, index=False)
    (out_dir / "README_SYNTHETIC.txt").write_text(
        "This folder contains SYNTHETIC data generated by src/data/synthetic.py for software\n"
        "validation only. It is NOT Low Carbon London data and no result derived from it is a\n"
        "project result.\n")
    return path
